import { useState } from 'react';
import { useQueryClient } from '@tanstack/react-query';
import { toast } from 'react-hot-toast';
import { Bell, CheckCheck } from 'lucide-react';
import { PageHeader } from '@/components/common/PageHeader';
import { ErrorPanel } from '@/components/common/ErrorPanel';
import { Badge, Button, Card, CardContent, DataTable, Pagination, type DataTableColumn } from '@/components/ui';
import { api, ApiError } from '@/lib/api';
import { useApiEnvelope } from '@/lib/hooks';
import type { NotificationItem, Page as PageType } from '@/lib/types';
import { formatDate, titleCase } from '@/lib/utils';

export function NotificationsPage({ portal }: { portal: string }) {
  const queryClient = useQueryClient();
  const [page, setPage] = useState(1);
  const [unreadOnly, setUnreadOnly] = useState(false);
  const [busy, setBusy] = useState(false);
  const notifications = useApiEnvelope<PageType<NotificationItem>>('notifications', '/notifications', {
    page,
    page_size: 20,
    unread_only: unreadOnly,
  });

  const invalidate = () => {
    void notifications.refetch();
    void queryClient.invalidateQueries({ queryKey: ['notifications'] });
    void queryClient.invalidateQueries({ queryKey: ['notification-unread-count'] });
  };

  const markRead = async (id: string) => {
    try {
      await api.patch(`/notifications/${id}/read`);
      invalidate();
    } catch (error) {
      toast.error(error instanceof ApiError ? error.message : 'Could not update notification');
    }
  };

  const markAll = async () => {
    setBusy(true);
    try {
      const response = await api.post('/notifications/mark-all-read');
      toast.success(response.message);
      invalidate();
    } catch (error) {
      toast.error(error instanceof ApiError ? error.message : 'Could not update notifications');
    } finally {
      setBusy(false);
    }
  };

  const columns: DataTableColumn<NotificationItem>[] = [
    {
      key: 'title',
      header: 'Notification',
      render: (row) => (
        <div className={row.read ? '' : 'font-semibold'}>
          <p>{row.title}</p>
          <p className="mt-0.5 text-xs font-normal text-muted-foreground">{row.message}</p>
        </div>
      ),
    },
    { key: 'category', header: 'Category', render: (row) => <Badge variant="outline">{titleCase(row.category)}</Badge> },
    { key: 'date', header: 'Received', render: (row) => formatDate(row.created_at, true) },
    {
      key: 'status',
      header: 'Status',
      render: (row) => <Badge variant={row.read ? 'secondary' : 'warning'}>{row.read ? 'Read' : 'Unread'}</Badge>,
    },
    {
      key: 'action',
      header: '',
      render: (row) => row.read ? <span className="text-xs text-muted-foreground">—</span> : (
        <Button variant="ghost" size="sm" onClick={() => markRead(row.id)}>Mark read</Button>
      ),
    },
  ];

  const data = notifications.data?.data;
  return (
    <>
      <PageHeader
        eyebrow={`${portal} portal`}
        title="Notifications"
        description="Announcements, result alerts and workflow updates delivered to your account."
        actions={
          <>
            <Button variant={unreadOnly ? 'default' : 'outline'} size="sm" onClick={() => { setUnreadOnly((value) => !value); setPage(1); }}>
              {unreadOnly ? 'Showing unread' : 'Show unread only'}
            </Button>
            <Button variant="outline" size="sm" onClick={markAll} loading={busy}><CheckCheck className="h-4 w-4" /> Mark all read</Button>
          </>
        }
      />
      <ErrorPanel error={notifications.error} onRetry={invalidate} />
      <Card>
        <CardContent className="p-4 sm:p-5">
          {notifications.isLoading ? <div className="h-48 animate-pulse rounded bg-muted" /> : (
            <>
              <DataTable columns={columns} data={data?.items ?? []} rowKey={(row) => row.id} empty="Your inbox is empty." compact />
              {data && data.total > 0 && (
                <div className="mt-5">
                  <Pagination page={data.page} pages={data.pages} total={data.total} onChange={setPage} />
                </div>
              )}
            </>
          )}
        </CardContent>
      </Card>
      <p className="mt-4 flex items-center gap-2 text-xs text-muted-foreground"><Bell className="h-3.5 w-3.5" /> Notifications are generated by server-side workflow events.</p>
    </>
  );
}
